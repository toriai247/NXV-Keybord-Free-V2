    private val banglishKeysByChar: Map<Char, List<String>> by lazy {
        BANGLISH_MAP.keys.groupBy { it.first().lowercaseChar() }
    }

    /**
     * Look up suggestions for Romanized Banglish input (e.g. k -> ki, koro, koy).
     */
    fun getBanglishRomanSuggestions(prefix: String, maxCount: Int = 4): List<String> {
        val clean = prefix.trim().lowercase()
        if (clean.isEmpty()) return emptyList()

        val candidateKeys = banglishKeysByChar[clean.first()] ?: BANGLISH_MAP.keys
        val matches = candidateKeys.filter { it.startsWith(clean) && it != clean }
            .take(maxCount)
        return matches
    }

    /**
     * Get candidate Bengali translations for Banglish prefix (e.g. k -> কি, করো, কই).
     */
    fun getBengaliFromBanglish(prefix: String, maxCount: Int = 4): List<String> {
        val clean = prefix.trim().lowercase()
        if (clean.isEmpty()) return emptyList()

        val results = LinkedHashSet<String>()
        // Exact match
        BANGLISH_MAP[clean]?.let { results.add(it) }

        // Prefix matches
        val candidateKeys = banglishKeysByChar[clean.first()] ?: BANGLISH_MAP.keys
        for (key in candidateKeys) {
            if (key.startsWith(clean)) {
                BANGLISH_MAP[key]?.let { results.add(it) }
                if (results.size >= maxCount) break
            }
        }
        return results.take(maxCount)
    }
