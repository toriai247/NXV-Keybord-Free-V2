    private val wordsByPrefix: Map<Char, List<String>> by lazy {
        WORDS.groupBy { it.first() }
    }

    /**
     * Finds native Bangla word completions starting with prefix.
     */
    fun getSuggestions(prefix: String, maxCount: Int = 5): List<String> {
        val query = prefix.trim()
        if (query.isEmpty()) return emptyList()

        val candidateList = wordsByPrefix[query.first()] ?: WORDS
        val exactMatches = candidateList.filter { it.startsWith(query) && it != query }
        return exactMatches.take(maxCount)
    }
